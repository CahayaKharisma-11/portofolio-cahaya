let currentLang = 'id';
let toastTimeout;

// 1. Switch Language (ID / EN)
function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  document.documentElement.lang = lang;

  const btnId = document.getElementById('btn-lang-id');
  const btnEn = document.getElementById('btn-lang-en');

  if (btnId && btnEn) {
    btnId.classList.toggle('lang-btn-active', lang === 'id');
    btnId.classList.toggle('lang-btn-inactive', lang !== 'id');
    btnEn.classList.toggle('lang-btn-active', lang === 'en');
    btnEn.classList.toggle('lang-btn-inactive', lang !== 'en');
  }

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });
}

// 2. Mobile Navigation Drawer
function initMobileMenu() {
  const mobileMenuBtn = document.getElementById('mobile-menu-btn');
  const mobileMenu = document.getElementById('mobile-menu');

  if (!mobileMenuBtn || !mobileMenu) return;

  mobileMenuBtn.addEventListener('click', () => {
    mobileMenu.classList.toggle('hidden');
  });

  document.querySelectorAll('.mobile-nav-link').forEach((link) => {
    link.addEventListener('click', () => {
      mobileMenu.classList.add('hidden');
    });
  });
}

// 3. Lightbox Preview Modal
function openLightbox(mediaContainerId, titleKey) {
  const source = document.getElementById(mediaContainerId);
  const modal = document.getElementById('lightbox-modal');
  const content = document.getElementById('lightbox-content');
  const title = document.getElementById('lightbox-title');

  if (!source || !modal || !content || !title) return;

  title.textContent = translations[currentLang][titleKey] || 'Preview';
  content.innerHTML = '';

  const img = source.querySelector('img');
  if (img && img.style.display !== 'none' && img.complete && img.naturalWidth > 0) {
    const fullImg = document.createElement('img');
    fullImg.src = img.src;
    fullImg.alt = img.alt;
    fullImg.className = 'max-h-[72vh] w-auto rounded-2xl object-contain shadow-md';
    content.appendChild(fullImg);
  } else {
    const clone = source.cloneNode(true);
    const hiddenFallback = clone.querySelector('.hidden');
    if (hiddenFallback) hiddenFallback.classList.remove('hidden');
    clone.className = 'w-full max-w-2xl rounded-2xl overflow-hidden shadow-md';
    content.appendChild(clone);
  }

  modal.classList.remove('hidden');
  document.body.style.overflow = 'hidden';
}

function closeLightbox() {
  const modal = document.getElementById('lightbox-modal');
  if (!modal) return;

  modal.classList.add('hidden');
  document.body.style.overflow = '';
}

// 4. Copy Email to Clipboard & Show Toast
async function copyEmail() {
  const emailEl = document.getElementById('email-text');
  if (!emailEl) return;

  const emailText = emailEl.textContent.trim();

  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(emailText);
    } else {
      const tempInput = document.createElement('textarea');
      tempInput.value = emailText;
      tempInput.style.position = 'fixed';
      tempInput.style.opacity = '0';
      document.body.appendChild(tempInput);
      tempInput.select();
      document.execCommand('copy');
      document.body.removeChild(tempInput);
    }
    showToast(translations[currentLang].toast_copied);
  } catch (err) {
    showToast(emailText);
  }
}

function showToast(message) {
  const toast = document.getElementById('toast');
  const toastMsg = document.getElementById('toast-message');
  if (!toast || !toastMsg) return;

  toastMsg.textContent = message;
  toast.classList.remove('toast-hidden');
  toast.classList.add('toast-visible');

  clearTimeout(toastTimeout);
  toastTimeout = setTimeout(() => {
    toast.classList.remove('toast-visible');
    toast.classList.add('toast-hidden');
  }, 2800);
}

// 5. Initialize on DOM Ready
document.addEventListener('DOMContentLoaded', () => {
  initMobileMenu();

  const yearEl = document.getElementById('current-year');
  if (yearEl) {
    yearEl.textContent = new Date().getFullYear();
  }

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeLightbox();
  });
});